-- =====================================================================
-- 1. ESTRUTURA
-- =====================================================================

DROP PROCEDURE IF EXISTS sp_registrar_matricula(INT, VARCHAR, VARCHAR, DATE, INT);
DROP FUNCTION  IF EXISTS fn_inadimplentes(VARCHAR);

DROP TABLE IF EXISTS pagamento;
DROP TABLE IF EXISTS tamanhos;
DROP TABLE IF EXISTS matriculas;
DROP TABLE IF EXISTS clientes;

CREATE TABLE clientes (
    id              SERIAL PRIMARY KEY,
    nome            VARCHAR(150) NOT NULL,
    idade           SMALLINT NOT NULL CHECK (idade > 0),
    cpf             VARCHAR(14) NOT NULL UNIQUE,
    endereco        VARCHAR(255) NOT NULL
);

CREATE TABLE matriculas (
    id              SERIAL PRIMARY KEY,
    cliente_id      INT NOT NULL REFERENCES clientes(id),
    modalidade      VARCHAR(20) NOT NULL CHECK (modalidade IN ('Jiu-Jitsu','Judo','Muay Thai','Karate','Boxe','Personal')),
    faixa           VARCHAR(20) NOT NULL,
    data_inicio     DATE NOT NULL
);

CREATE TABLE tamanhos (
    id              SERIAL PRIMARY KEY,
    cliente_id      INT NOT NULL REFERENCES clientes(id),
    tamanho_faixa   VARCHAR(5) NOT NULL,
    tamanho_kimono  VARCHAR(5) NOT NULL
);

CREATE TABLE pagamento (
    id                  SERIAL PRIMARY KEY,
    cliente_id          INT NOT NULL REFERENCES clientes(id),
    dia_pagamento       SMALLINT NOT NULL CHECK (dia_pagamento BETWEEN 1 AND 28),
    plano               VARCHAR(10) NOT NULL CHECK (plano IN ('Mensal','Anual')),
    forma_pagamento     VARCHAR(10) NOT NULL CHECK (forma_pagamento IN ('Credito','Debito')),
    ativo               BOOLEAN NOT NULL,
    status_pagamento    VARCHAR(10) NOT NULL CHECK (status_pagamento IN ('Pago','Devendo'))
);


