-- ---------------------------------------------------------------------
-- 3.1 INDICE
-- O PostgreSQL nao cria indice automaticamente para chaves estrangeiras.
-- (cliente_id, modalidade) atende, com uma unica estrutura:
--   * junções clientes -> matriculas (coluna lider cliente_id);
--   * "o cliente ja esta matriculado nesta modalidade?" (as duas colunas),
--     consulta usada pela procedure abaixo e pelo MatriculaService do app.
-- ---------------------------------------------------------------------
CREATE INDEX idx_matriculas_cliente_modalidade
    ON matriculas (cliente_id, modalidade);

-- ---------------------------------------------------------------------
-- 3.2 FUNCTION
-- Lista os clientes inadimplentes: pagamento ATIVO e status 'Devendo'.
-- Parametro opcional filtra por modalidade (NULL = todas).
--   SELECT * FROM fn_inadimplentes();
--   SELECT * FROM fn_inadimplentes('Jiu-Jitsu');
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_inadimplentes(p_modalidade VARCHAR DEFAULT NULL)
RETURNS TABLE (
    cliente_id     INT,
    nome           VARCHAR,
    cpf            VARCHAR,
    modalidade     VARCHAR,
    plano          VARCHAR,
    dia_pagamento  SMALLINT
)
LANGUAGE sql
STABLE
AS $$
    SELECT c.id, c.nome, c.cpf, m.modalidade, p.plano, p.dia_pagamento
      FROM clientes   c
      JOIN pagamento  p ON p.cliente_id = c.id
      JOIN matriculas m ON m.cliente_id = c.id
     WHERE p.ativo
       AND p.status_pagamento = 'Devendo'
       AND (p_modalidade IS NULL OR m.modalidade = p_modalidade)
     ORDER BY c.nome, m.modalidade;
$$;

-- ---------------------------------------------------------------------
-- 3.3 PROCEDURE
-- Registra uma matricula aplicando as regras de negocio e devolve o id
-- gerado em p_matricula_id (parametro INOUT).
-- Regras (as mesmas do MatriculaService do app Laravel):
--   * o cliente precisa existir;
--   * Boxe, Muay Thai e Personal nao tem graduacao: faixa fica 'N/A';
--   * as demais modalidades exigem uma faixa valida (nunca 'N/A');
--   * o cliente nao pode ter duas matriculas na mesma modalidade.
--
--   CALL sp_registrar_matricula(10, 'Judo', 'Amarela', CURRENT_DATE, NULL);
-- ---------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE sp_registrar_matricula(
    IN    p_cliente_id   INT,
    IN    p_modalidade   VARCHAR,
    IN    p_faixa        VARCHAR,
    IN    p_data_inicio  DATE DEFAULT CURRENT_DATE,
    INOUT p_matricula_id INT  DEFAULT NULL
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_faixa VARCHAR(20) := p_faixa;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM clientes WHERE id = p_cliente_id) THEN
        RAISE EXCEPTION 'Cliente % nao encontrado.', p_cliente_id;
    END IF;

    IF p_modalidade IN ('Boxe', 'Muay Thai', 'Personal') THEN
        v_faixa := 'N/A';
    ELSIF v_faixa IS NULL OR v_faixa NOT IN
          ('Branca','Cinza','Amarela','Laranja','Verde','Azul','Roxa','Marrom','Preta') THEN
        RAISE EXCEPTION 'Faixa invalida para %: %.', p_modalidade, COALESCE(v_faixa, 'NULL');
    END IF;

    IF EXISTS (SELECT 1 FROM matriculas
                WHERE cliente_id = p_cliente_id AND modalidade = p_modalidade) THEN
        RAISE EXCEPTION 'O cliente % ja possui matricula em %.', p_cliente_id, p_modalidade;
    END IF;

    INSERT INTO matriculas (cliente_id, modalidade, faixa, data_inicio)
    VALUES (p_cliente_id, p_modalidade, v_faixa, COALESCE(p_data_inicio, CURRENT_DATE))
    RETURNING id INTO p_matricula_id;
END;
$$;

-- ---------------------------------------------------------------------
-- 3.4 PROCEDURE
-- Troca o status dos pagamentos ATIVOS de um plano, de uma so vez
-- (ex.: marcar como 'Pago' todos os planos anuais que estavam 'Devendo').
-- Pagamentos inativos nunca sao alterados. E a mesma operacao de
-- PagamentoService::atualizarStatus() no app Laravel.
--
--   CALL atualizar_pagamento('Devendo', 'Anual', 'Pago');
-- ---------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE atualizar_pagamento(
    p_status_pagamento VARCHAR DEFAULT 'Devendo',
    p_plano            VARCHAR DEFAULT 'Anual',
    p_pagamento_novo   VARCHAR DEFAULT 'Pago'
)
LANGUAGE plpgsql
AS $$
BEGIN
    UPDATE pagamento
       SET status_pagamento = p_pagamento_novo
     WHERE status_pagamento = p_status_pagamento
       AND plano = p_plano
       AND ativo = TRUE;
END;
$$;

-- ---------------------------------------------------------------------
-- 3.5 TRIGGER
-- Nao deixa um pagamento INATIVO ficar com status 'Pago'. Roda antes de
-- cada UPDATE; a regra fica no banco e vale mesmo para quem nao passa
-- pelo app. (O app tambem valida isso em PagamentoRequest.)
--
-- So atua em UPDATE: as linhas ja existentes que estejam inativas e 'Pago'
-- continuam la, mas qualquer UPDATE que as mantenha assim e recusado. Para
-- corrigir uma delas, mude o status para 'Devendo' ou marque como ativa.
--
--   UPDATE pagamento SET ativo = FALSE, status_pagamento = 'Pago' WHERE id = 1;
--   -- ERRO: O cliente 1 esta inativo e nao pode ter o pagamento como Pago
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION bloqueia_pagamento()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.ativo = FALSE AND NEW.status_pagamento = 'Pago' THEN
        RAISE EXCEPTION
            'O cliente % esta inativo e nao pode ter o pagamento como Pago',
            NEW.cliente_id;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_bloqueio_pagamento ON pagamento;

CREATE TRIGGER trg_bloqueio_pagamento
BEFORE UPDATE ON pagamento
FOR EACH ROW
EXECUTE FUNCTION bloqueia_pagamento();

